/**
 * IndustrialIcon Component
 * @param {string} name - Icon name (e.g., 'qc-worker', 'forklift')
 * @param {string} variant - 'line' or 'glyph' (default: 'line')
 * @param {number} size - Icon size in pixels (default: 24)
 * @param {string} color - Color preset name or 'inherit' (default: 'inherit')
 * @param {string} className - Additional CSS classes
 * @param {object} style - Additional inline styles
 */
const IndustrialIcon = ({
    name,
    variant = 'line',
    size = 24,
    color = 'inherit',
    className = '',
    style = {}
}) => {
    const iconSrc = icons[variant]?.[name];

    if (!iconSrc) {
        console.warn(`IndustrialIcon: Icon "${name}" not found in variant "${variant}"`);
        return null;
    }

    const filterStyle = color === 'inherit'
        ? {}
        : { filter: colorFilters[color] || colorFilters.white };

    return (
        <img
            src={iconSrc}
            alt={name}
            className={`industrial-icon industrial-icon-${color} ${className}`}
            style={{
                width: size,
                height: size,
                ...filterStyle,
                ...style
            }}
        />
    );
};

export default IndustrialIcon;
